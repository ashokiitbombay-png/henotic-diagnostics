// Fast O(1) slug and pincode lookup indices
export const LOCATION_BY_SLUG: Record<string, LocationItem> = {};
export const LOCATION_BY_COMPOSITE_KEY: Record<string, LocationItem> = {};
export const LOCATIONS_BY_PINCODE: Record<string, LocationItem[]> = {};
export const LOCATIONS_BY_REGION: Record<string, LocationItem[]> = {};
export const LOCATIONS_BY_CITY: Record<string, LocationItem[]> = {};

for (const loc of LOCATION_DATABASE) {
  // Primary slug index (first occurrence wins for top-level lookup)
  if (!LOCATION_BY_SLUG[loc.slug]) {
    LOCATION_BY_SLUG[loc.slug] = loc;
  }
  // Composite key: region/slug for exact disambiguation (e.g. raigad/old-panvel vs navi-mumbai/old-panvel)
  LOCATION_BY_COMPOSITE_KEY[`${loc.region}/${loc.slug}`] = loc;

  // Group by pincode
  if (!LOCATIONS_BY_PINCODE[loc.pincode]) {
    LOCATIONS_BY_PINCODE[loc.pincode] = [];
  }
  LOCATIONS_BY_PINCODE[loc.pincode].push(loc);

  // Group by region
  if (!LOCATIONS_BY_REGION[loc.region]) {
    LOCATIONS_BY_REGION[loc.region] = [];
  }
  LOCATIONS_BY_REGION[loc.region].push(loc);

  // Group by city
  if (!LOCATIONS_BY_CITY[loc.city]) {
    LOCATIONS_BY_CITY[loc.city] = [];
  }
  LOCATIONS_BY_CITY[loc.city].push(loc);
}

/**
 * Lookup location by slug, optionally scoped to region for disambiguation
 */
export function getLocationBySlug(slug: string, regionSlug?: string): LocationItem | undefined {
  if (regionSlug && LOCATION_BY_COMPOSITE_KEY[`${regionSlug}/${slug}`]) {
    return LOCATION_BY_COMPOSITE_KEY[`${regionSlug}/${slug}`];
  }
  return LOCATION_BY_SLUG[slug];
}

/**
 * Lookup locations by 6-digit postal PIN code
 */
export function getLocationsByPincode(pincode: string): LocationItem[] {
  const cleanPin = pincode.trim();
  return LOCATIONS_BY_PINCODE[cleanPin] || [];
}

/**
 * Lookup locations by City name
 */
export function getLocationsByCity(city: string): LocationItem[] {
  return LOCATIONS_BY_CITY[city] || [];
}

/**
 * Lookup locations by Region slug
 */
export function getLocationsByRegion(regionSlug: string): LocationItem[] {
  return LOCATIONS_BY_REGION[regionSlug] || [];
}

/**
 * Universal Search: Searches locations by name, pincode, city, or region
 */
export function searchLocations(query: string): LocationItem[] {
  if (!query || query.trim().length === 0) return LOCATION_DATABASE;
  const q = query.toLowerCase().trim();
  return LOCATION_DATABASE.filter(loc =>
    loc.name.toLowerCase().includes(q) ||
    loc.slug.toLowerCase().includes(q) ||
    loc.pincode.includes(q) ||
    loc.city.toLowerCase().includes(q) ||
    loc.regionName.toLowerCase().includes(q)
  );
}

